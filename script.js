//animation cho đoạn giống vs code đánh chữ
// Thêm vào cuối file script.js
function initializeCodeAnimation() {
  const codeLines = document.querySelectorAll(".code-line");
  const cursor = document.querySelector(".cursor");
  let currentLine = 0;
  let currentChar = 0;
  let allChars = [];
  let positions = [];

  // Tạo các phần tử span cho từng ký tự
  codeLines.forEach((line, lineIndex) => {
    const spans = line.querySelectorAll("span");

    spans.forEach((span) => {
      const originalText = span.textContent;
      span.textContent = "";
      const spanClass = span.className;

      // Tách từng ký tự và tạo span mới
      for (let i = 0; i < originalText.length; i++) {
        const charSpan = document.createElement("span");
        charSpan.className = spanClass + " char";
        charSpan.textContent = originalText[i];
        span.appendChild(charSpan);

        allChars.push({
          element: charSpan,
          line: lineIndex,
        });

        // Tính toán vị trí sau khi DOM được cập nhật
        setTimeout(() => {
          const rect = charSpan.getBoundingClientRect();
          const lineRect = line.getBoundingClientRect();
          positions.push({
            left: rect.right - lineRect.left,
            top: rect.top - cursor.parentElement.getBoundingClientRect().top,
          });
        }, 0);
      }
    });
  });

  // Hàm đánh chữ
  function typeNextCharacter() {
    if (currentChar < allChars.length) {
      const char = allChars[currentChar];

      // Hiển thị dòng nếu cần
      if (!codeLines[char.line].classList.contains("typing")) {
        codeLines[char.line].classList.add("typing");
      }

      // Hiển thị ký tự
      char.element.classList.add("typing");

      // Di chuyển con trỏ (đợi vị trí được tính toán)
      setTimeout(() => {
        if (positions[currentChar]) {
          cursor.style.left = positions[currentChar].left + "px";
          cursor.style.top = positions[currentChar].top + "px";
        }
      }, 10);

      currentChar++;

      // Tiếp tục đánh chữ với tốc độ chậm hơn
      setTimeout(typeNextCharacter, Math.random() * 150 + 100); // Tốc độ chậm hơn
    } else {
      // Khi hoàn thành, đợi lâu hơn và bắt đầu lại
      setTimeout(resetAnimation, 5000); // Đợi lâu hơn trước khi reset
    }
  }

  // Hàm reset animation
  function resetAnimation() {
    // Ẩn tất cả các dòng và ký tự
    codeLines.forEach((line) => {
      line.classList.remove("typing");
    });

    allChars.forEach((char) => {
      char.element.classList.remove("typing");
    });

    // Reset con trỏ về vị trí đầu
    cursor.style.left = "0px";
    cursor.style.top = "0px";

    // Reset biến đếm
    currentChar = 0;

    // Bắt đầu lại animation sau một khoảng thời gian
    setTimeout(typeNextCharacter, 2000); // Đợi lâu hơn trước khi bắt đầu lại
  }

  // Bắt đầu animation sau khi vị trí được tính toán
  setTimeout(() => {
    typeNextCharacter();
  }, 1000);
}

// Thêm vào hàm document.addEventListener('DOMContentLoaded', ...)
document.addEventListener("DOMContentLoaded", function () {
  // Các hàm khởi tạo khác...

  // Khởi tạo animation code
  initializeCodeAnimation();
});
